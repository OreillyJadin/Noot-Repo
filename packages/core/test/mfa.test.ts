// Run: pnpm test
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { normalizeTotpCode, svgFromDataUri } from '../src/auth/mfa.ts';

test('TOTP codes accept spaces and dashes but must contain six digits', () => {
  assert.equal(normalizeTotpCode('123456'), '123456');
  assert.equal(normalizeTotpCode(' 123 456 '), '123456');
  assert.equal(normalizeTotpCode('123-456'), '123456');
  assert.equal(normalizeTotpCode('12345'), null);
  assert.equal(normalizeTotpCode('1234567'), null);
  assert.equal(normalizeTotpCode('abcdef'), null);
  assert.equal(normalizeTotpCode(''), null);
});

test('SVG data URIs are decoded into SVG markup', () => {
  const svg = '<svg xmlns="http://www.w3.org/2000/svg">é</svg>';
  assert.equal(svgFromDataUri(`data:image/svg+xml;utf-8,${svg}`), svg);
  assert.equal(svgFromDataUri(`data:image/svg+xml;utf-8,${encodeURIComponent(svg)}`), svg);
  assert.equal(svgFromDataUri(`data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`), svg);
  assert.equal(
    svgFromDataUri(`data:image/svg+xml;utf-8,<?xml version="1.0"?>\n<!-- Generated by SVGo -->\n${svg}`),
    svg,
  );
});
